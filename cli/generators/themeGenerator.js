
import { writeFile } from "node:fs/promises";
import path from "node:path";

const DESIGN_SYSTEM_TOKENS = {
  primary: "--color-primary",
  secondary: "--color-secondary",
  container: "--size-container-lg",
};

const generateTheme = async (config, projectDirectory) => {
  const { primary, secondary } = config.theme;
  const containerWidth = config.container.width;

  const css = `/* Generated by MY Bharat Design System CLI */

:root {
  ${DESIGN_SYSTEM_TOKENS.primary}: ${primary};
  ${DESIGN_SYSTEM_TOKENS.secondary}: ${secondary};
  ${DESIGN_SYSTEM_TOKENS.container}: ${containerWidth};
}
`;

  const filePath = path.join(
    projectDirectory,
    "mybharat-theme.css"
  );

  await writeFile(filePath, css, "utf-8");

  return filePath;
};

export default generateTheme;
